"""Deterministic circular-orbit plots; coordinates are generated, never hand sketched."""
from pathlib import Path
import math
import json

ROOT = Path(__file__).resolve().parent
K = 1.524
WE = 2*math.pi/365.2564
WM = WE*K**-1.5


def apparent(t, inclination=0):
    """Node is -90 degrees; Mars is at maximum ecliptic latitude at t=0."""
    c, s = math.cos, math.sin
    x = K*c(inclination)*c(WM*t)-c(WE*t)
    y = K*s(WM*t)-s(WE*t)
    z = K*s(inclination)*c(WM*t)
    vx = -K*c(inclination)*WM*s(WM*t)+WE*s(WE*t)
    vy = K*WM*c(WM*t)-WE*c(WE*t)
    return math.degrees(math.atan2(y,x)), math.degrees(math.atan2(z,math.hypot(x,y))), (x*vy-y*vx)/(x*x+y*y)


def coordinates(lo,hi,fn,n=160):
    return ' '.join('({:.7f},{:.7f})'.format(*fn(lo+(hi-lo)*j/n)) for j in range(n+1))


def main():
    inc=math.radians(1.85)
    lo,hi=0.,70.
    for _ in range(60):
        mid=(lo+hi)/2
        if apparent(mid,inc)[2] < 0: lo=mid
        else: hi=mid
    stationary=(lo+hi)/2
    def xy(t):
        lon,lat,_=apparent(t,inc)
        return lon/5.,(lat-3.1)*1.15
    tex=['% Generated by generate_ch04_geometry.py.']
    tex.append(r'\newcommand{\MarsCoplanarPath}{\draw[kcurve] plot coordinates {'+
               coordinates(-90,90,lambda t:(t/27,apparent(t)[0]/12),240)+'};}')
    parts=[]
    for a,b,color in [(-110,-stationary,'TextGray'),(-stationary,stationary,'DeepBlue'),(stationary,110,'TextGray')]:
        parts.append(r'\draw['+color+',thick] plot coordinates {'+coordinates(a,b,xy)+'};')
    for t in [-85,-10,85]:
        parts.append(r'\draw[->,DeepBlue,thick] plot coordinates {'+coordinates(t,t+4,xy,8)+'};')
    tex.append(r'\newcommand{\MarsInclinedPath}{'+'\n'.join(parts)+'}')
    out=ROOT/'data/ch04-mars-paths.tex'; out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text('\n'.join(tex)+'\n')
    report={'stationary_inclined_days':stationary,'inclination_deg':1.85,
            'endpoints':[{'t':t,'longitude_deg':apparent(t,inc)[0],'latitude_deg':apparent(t,inc)[1]} for t in [-110,0,110]],
            'coplanar_stationary_days':math.acos((K*K*K**-1.5+1)/(K*(1+K**-1.5)))/(WE-WM)}
    print(json.dumps(report))


if __name__=='__main__':
    main()
