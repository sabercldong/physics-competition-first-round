"""Deterministic potential curve, and independent checks of Chapter 8 geometry."""
import math, json, hashlib
from pathlib import Path

ROOT=Path(__file__).resolve().parents[4]
UNIT=ROOT/'sample/xes-original/eleventh-section'
BUILD=Path(__file__).resolve().parents[1]/'build/review-ch08-20260909'
def ei_negative(z):
    # Convergent series; the plotted range 0.26 <= z <= 2.73 is well conditioned.
    term=-z; total=term
    for n in range(2,65):
        term *= -z/n
        total += term/n
    return 0.5772156649015329+math.log(z)+total
def potential(r):
    alpha=.65
    return -(math.exp(-alpha*r)/r+alpha*ei_negative(alpha*r))
def main():
    points=[(.4+i*3.8/190, potential(.4+i*3.8/190)) for i in range(191)]
    path='--'.join(f'({x:.8f},{y:.8f})' for x,y in points)
    (UNIT/'geometry-data.tex').write_text('% Generated by tools/generate_ch08_geometry.py\n'
        '\\newcommand{\\screenedPotentialCurve}{\\draw[solpath] '+path+';}\n')
    errors=[]
    for r in [.4,.7,1,2,4]:
        eps=1e-5
        derivative=(potential(r+eps)-potential(r-eps))/(2*eps)
        errors.append(abs(derivative-math.exp(-.65*r)/r**2))
    assert max(errors)<1e-7
    R=1; c=2/3; s=math.sqrt(5)/3; u=math.sqrt(2/3)
    ux=u*c; uy=-u*s; t=uy+math.sqrt(uy*uy+2*c)
    landing=s+ux*t
    assert abs(s*ux+c*uy)<1e-14
    assert abs(landing-(5*math.sqrt(5)+4*math.sqrt(23))/27)<1e-14
    c=-1/math.sqrt(3); s=math.sqrt(1-c*c); u=math.sqrt(-c)
    ux=u*c; uy=u*s; t=-s/ux
    hit_residuals=[s+ux*t,-c+uy*t-t*t/2]
    assert all(abs(x)<1e-14 for x in hit_residuals)
    assert abs(s*ux-c*uy)<1e-14
    # Inner-wall trajectory lies inside the circle through its first apex.
    c=-.8; s=math.sqrt(1-c*c); u=math.sqrt(-c); apex=u*s
    radii=[(s+u*c*tt)**2+(-c+u*s*tt-tt*tt/2)**2 for tt in [apex*i/100 for i in range(101)]]
    assert max(radii)<1+1e-12
    BUILD.mkdir(parents=True,exist_ok=True)
    (BUILD/'geometry-checks.json').write_text(json.dumps({
        'potential_derivative_max_error':max(errors), 'outer_landing_over_R':landing,
        'inner_center_hit_residuals':hit_residuals, 'inner_apex_max_radius_squared':max(radii),
        'checks_passed':True,
        'source_hashes':{str(p):hashlib.sha256(p.read_bytes()).hexdigest()
                         for folder in ['tenth-section','eleventh-section','thirteenth-section']
                         for p in (UNIT.parent/folder).glob('*.tex')}},indent=2))
if __name__=='__main__': main()
