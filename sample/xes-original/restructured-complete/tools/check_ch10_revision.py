"""Independent selected physics, source-link and figure-geometry checks.

Numerical tests supplement, and do not replace, a visual/teaching review.
Molecular panels are qualitative: only atom count, inversion directions and
panel inventory are checked, not a computed molecular force-field spectrum.
"""
from pathlib import Path
import hashlib,json,math,re
import numpy as np
BOOK=Path(__file__).resolve().parent.parent
BASE=BOOK/'build/review-ch10-20260909'
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def close(a,b,tol=1e-9):assert np.max(np.abs(np.array(a)-np.array(b)))<tol,(a,b)
def root(f,a,b):
    assert f(a)*f(b)<0
    for _ in range(80):
        c=(a+b)/2
        if f(a)*f(c)<=0:b=c
        else:a=c
    return (a+b)/2
r={}
# Phase tangent is generated from exactly the same parametrization.
for theta in np.linspace(0,2*math.pi,50):
    x,v=2.6*math.cos(theta),-1.55*math.sin(theta)
    dx,dv=-2.6*math.sin(theta),-1.55*math.cos(theta)
    assert x*dv-v*dx<0
    close(x*x/2.6**2+v*v/1.55**2,1)
r['phase_ellipse']='same-parametric-curve; clockwise tangent at all sampled phases'
# Pendulum rods generated by trigonometry and wedge contact from one slope.
for a in [28,23,-18,12,12*math.sqrt(2),-12*math.sqrt(2)]:
    close(math.sin(math.radians(a))**2+math.cos(math.radians(a))**2,1)
T=np.array([3.8,3.]);P=np.array([2.65,1.85]);normal=np.array([-.7,.7])
close(np.dot(T-P,normal),0);close((T-P)[0],(T-P)[1])
close(np.linalg.norm(T-P)/math.sqrt(2),1.15)
close(.8-np.linalg.norm(T-P)/math.sqrt(2),2.65-3)
r['wedge_geometry']={'angle_deg':45,'point_on_incline':True,'normal_dot_tangent':0,'q':-.35}
close(2**2+2**2,8)
r['governor_geometry']={'rho':2,'y':4,'l_squared':8,'relation':'rho^2+y^2/4=l^2'}
close(4.5,2.5+2);close(.125-.125,0);close(.125+.2*11+.125,2.45)
close(5.95-2.55,3.4);close(5.1-3.4,3.4/2)
r['chain_and_cell']='H=x+s; lower link reaches floor; diatomic cell is twice nearest-neighbour distance'
# Three-charge Hessians, including the rigid zero modes.
Ha=5/(12*math.sqrt(3))*(3*np.eye(3)-np.ones((3,3)))
Hz=np.ones((3,3))/(3*math.sqrt(3))
close(np.linalg.eigvalsh(Ha),[0,5*math.sqrt(3)/12,5*math.sqrt(3)/12])
close(np.linalg.eigvalsh(Hz),[0,0,math.sqrt(3)/3])
r['charges']={'Ha_eigenvalues':np.linalg.eigvalsh(Ha).tolist(),'Hz_eigenvalues':np.linalg.eigvalsh(Hz).tolist()}
M=np.array([[2,1],[1,1]]);K=np.diag([2,1])
for sign in [-1,1]:
    lam=2+sign*math.sqrt(2);a=np.array([1,-sign*math.sqrt(2)])
    close(K@a,lam*M@a)
r['double_pendulum']=[2-math.sqrt(2),2+math.sqrt(2)]
C=np.roll(np.eye(6),1,axis=0);D=2*np.eye(6)-C-C.T
a=np.array([1,1,0,-1,-1,0]);b=np.array([1,-1,0,1,-1,0])
close(C@C@a,C@a-a);close(C@C@b,-C@b-b)
close(np.linalg.eigvalsh(D),[0,1,1,3,3,4])
for s,t,x in [(-1,-1,np.ones(6)),(1,-1,np.array([1,-1,1,-1,1,-1])),(-1,1,a),(1,1,b)]:
    close(-x[(1-np.arange(6))%6],s*x);close(-x[(4-np.arange(6))%6],t*x)
r['six_ring']='eigenvalues 0,1,1,3,3,4; both rotation identities and four reflection sectors checked'
# Exact two-stage friction dynamics and work/energy balance.
M,m,k,mu,g,l0=3.6,1.8,24.,.3,10.,.3
w=math.sqrt(k*(1/M+1/m));theta=root(lambda z:z-4*math.sin(z),2,3)
t1=theta/w;r1=.6+.6*math.cos(theta);u1=-.6*w*math.sin(theta)
wB=math.sqrt(k/m);rB=l0+mu*m*g/k
tau=root(lambda t:rB+(r1-rB)*math.cos(wB*t)+u1/wB*math.sin(wB*t),0,.15)
vB=-(r1-rB)*wB*math.sin(wB*tau)+u1*math.cos(wB*tau)
xA=-.5*t1*t1-(m/(M+m))*(r1-1.2);xB=-.5*t1*t1+(M/(M+m))*(r1-1.2)
loss=mu*M*g*xA+mu*m*g*(-xB+r1)
res=.5*k*(1.2-l0)**2-(.5*k*l0*l0+.5*m*vB*vB+loss)
close(res,0);assert k*l0<mu*M*g
r['friction']={'time_s':t1+tau,'vA_m_s':0,'vB_m_s':vB,'energy_residual_J':res}
for gamma in [.05,.4,1,2]:
    lo=math.sqrt(1+gamma**2)-gamma;hi=math.sqrt(1+gamma**2)+gamma
    close(hi-lo,2*gamma)
    for w in [lo,hi]:close((1-w*w)**2,4*gamma**2*w*w)
r['bandwidth']='exact power FWHM=2gamma, checked below/above displacement-peak threshold'
# Compare exact spring-pendulum potential with its third-order expansion.
k,m,g,l0=4.,1.,1.,.75;L=l0+m*g/k;bcoef=k*l0/(2*L*L)
errs=[]
for eps in [.02,.01,.005]:
    x,y=eps,.7*eps;rr=math.hypot(x,L+y)
    exact=.5*k*(rr-l0)**2-m*g*y-.5*k*(L-l0)**2
    cubic=.5*m*g/L*x*x+.5*k*y*y+bcoef*x*x*y
    errs.append(abs(exact-cubic))
assert all(14<a/b<18 for a,b in zip(errs,errs[1:]))
close(k*l0,3*m*g)
r['spring_pendulum']={'remainder_errors':errs,'1_to_2_internal_resonance':'k*l0=3*m*g'}
# Source inventory and explicit figure references.
tex=(BOOK/'generated/chapters/ch10.tex').read_text()
labels=re.findall(r'\\label\{([^}]+)\}',tex)
assert len(labels)==len(set(labels))
figlabels=[s for s in labels if s.startswith('ch10:fig:')]
assert len(figlabels)==29
assert all(r'\ref{'+s+'}' in tex for s in figlabels)
assert tex.count(r'\begin{origexamplebox}')==tex.count(r'\begin{xesolution}')==9
assert 'fill=white' not in tex and 'fill=White' not in tex
ledger=json.loads((BOOK/'audit/source-review/ch10-revision-ledger.json').read_text())
objects=[o for s in ledger['sources'] for o in s['objects']]
assert len({o['source_object_id'] for o in objects})==len(objects)
for o in objects:
    assert o['status']=='mapped'
    for label in o.get('target_ids',[]):assert label in labels
assert sum(o['object_type']=='figure_group' for o in objects)==19
assert sum(o['object_type']=='figure_panel' for o in objects)==30
r['source_inventory']={'source_teaching_groups':len(objects),'source_figure_groups':19,'molecular_subpanels':30,
 'new_numbered_figure_groups':29,'examples_with_solutions':9,'all_figure_labels_referenced':True}
# Every opposite pair obeys the advertised g/u direction relationship.
mol=(BOOK/'chapters/new/ch10-benzene-modes.tex').read_text()
groups=re.split(r'\\chTenModeGroup\{',mol)[1:]
panels=[]
for group in groups:
    typ=re.search(r'\(([ABE])_\{([12])([gu])\}\)',group)
    assert typ,group[:100]
    parity=-1 if typ[3]=='g' else 1
    for plane,cs,hs in re.findall(r'\\chTenMolecule\{([01])\}\{([^}]+)\}\{([^}]+)\}\{\}',group):
        for array in [cs,hs]:
            if plane=='0':
                vals=list(map(int,array.split(',')))
                close(vals[3:],np.array(vals[:3])*parity)
            else:
                vals=[]
                for item in array.split(','):
                    angle,mag=map(float,item.split('/'))
                    vals.append(np.array([math.cos(math.radians(angle)),math.sin(math.radians(angle))])*(mag>0))
                close(vals[3:],np.array(vals[:3])*parity)
        panels.append(typ[0])
assert len(panels)==30
r['molecular_directions']={'panels':30,'opposite_pair_parity_checked':True,
 'limit':'qualitative directions only; no claim that these are force-field-calculated eigenvectors or measured amplitudes'}
paths=list((BOOK/'chapters/new').glob('ch10-*.tex'))+[BOOK/'generated/chapters/ch10.tex',BOOK/'assets/ch10/benzene-model.png',BOOK/'audit/source-review/ch10-revision-ledger.json']
r['source_hashes']={str(p):sha(p) for p in paths}
(BASE/'geometry-checks.json').write_text(json.dumps(r,ensure_ascii=False,indent=2))
